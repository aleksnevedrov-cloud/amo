/** Простой Markdown → HTML: заголовки, абзацы, списки, жирный. Достаточно для юридических текстов. */
export function markdownToHtml(md: string, title: string): string {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const inline = (s: string) => esc(s).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
  const blocks = md.trim().split(/\n{2,}/);
  const html = blocks
    .map((b) => {
      const h = /^(#{1,3})\s+(.*)$/.exec(b);
      if (h) {
        const level = (h[1] ?? '#').length;
        return `<h${level}>${inline(h[2] ?? '')}</h${level}>`;
      }
      if (b.split('\n').every((l) => /^- /.test(l))) return `<ul>${b.split('\n').map((l) => `<li>${inline(l.slice(2))}</li>`).join('')}</ul>`;
      return `<p>${inline(b.replace(/\n/g, ' '))}</p>`;
    })
    .join('\n');
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(title)}</title>
<style>body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;margin:40px auto;padding:0 16px;line-height:1.5;color:#222}h1{font-size:24px}h2{font-size:18px;margin-top:28px}</style></head><body>${html}</body></html>`;
}
